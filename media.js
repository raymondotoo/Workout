const escape = value => String(value).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
export function demoFor(exercise) {
  const demo = demos[exercise.name];
  if (!demo) throw new Error(`Missing demonstration: ${exercise.name}`);
  return demo;
}
export function embedUrl(demo, origin = '') {
  const params = new URLSearchParams({start:String(demo.start),end:String(demo.end),autoplay:'1',mute:'1',playsinline:'1',rel:'0'});
  if (origin) params.set('origin', origin);
  return `https://www.youtube-nocookie.com/embed/${demo.id}?${params}`;
}
export function thumbnail(exercise, index) {
  const demo = demoFor(exercise);
  return `<button class="exercise-art video-thumbnail" data-detail="${index}" aria-label="Watch ${escape(exercise.name)} demonstration"><img src="${escape(demo.thumbnail)}" alt="" loading="lazy" decoding="async" referrerpolicy="no-referrer"><span class="video-play" aria-hidden="true">▶</span><span class="video-badge" aria-hidden="true">30s DEMO</span></button>`;
}
export function videoGuide(exercise, online = true, origin = '') {
  const demo = demoFor(exercise);
  const media = online ? `<iframe id="exercise-video" src="${escape(embedUrl(demo, origin))}" title="${escape(exercise.name)} video demonstration" allow="autoplay; encrypted-media; picture-in-picture; fullscreen" referrerpolicy="strict-origin-when-cross-origin" allowfullscreen></iframe>` : '<div class="video-offline"><span aria-hidden="true">◉</span><strong>You’re offline</strong><p>Connect to watch the demonstration.<br>Your form cues and set tracking are still available.</p></div>';
  return `<div class="video-stage">${media}</div><div class="video-actions">${online?'<button class="secondary" id="replay-demo">↻ Replay clip</button>':''}<a class="video-source" href="${escape(demo.source)}" target="_blank" rel="noopener noreferrer">Watch full video ↗</a></div><p class="video-credit">Video by ${escape(demo.author)} · 30-second preview<br><span>Starts muted. Use the player to turn sound on.</span></p>`;
}
